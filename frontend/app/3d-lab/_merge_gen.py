"""Merge the two 3D registry chunks into simLoaders.ts + agentSims.json."""
import re
import json

entries = []
field_re = re.compile(
    r"(\w+):\s*('((?:\\.|[^'\\])*)'|\"((?:\\.|[^\"\\])*)\")")
NEEDED = ('id', 'title', 'subject', 'chapter', 'why3d', 'importPath')
for chunk in ('registryChunk_a.ts', 'registryChunk_b.ts'):
    src = open(f'components/simulations/three/{chunk}', encoding='utf-8').read()
    cur = {}
    for name, _q, sv, dv in field_re.findall(src):
        val = (sv if sv else dv).replace("\\'", "'").replace('\\"', '"')
        if name in cur and name == 'id':
            cur = {}
        cur[name] = val
        if name == 'importPath' and all(k in cur for k in NEEDED):
            entries.append({k: cur[k] for k in NEEDED})
            cur = {}
print('entries parsed:', len(entries))
assert len(entries) == 40, 'expected 40'

out = []
out.append("'use client';")
out.append('')
out.append('/** AUTO-GENERATED by the 3D wave merge - do not edit by hand.')
out.append(' *  Explicit dynamic imports for every agent-built 3D sim (webpack-safe). */')
out.append("import dynamic from 'next/dynamic'")
out.append('')
out.append('const loading = () => (')
out.append('  <div className="flex h-[420px] items-center justify-center rounded-2xl border border-white/10 bg-[#0a0a12]">')
out.append('    <div className="text-center">')
out.append('      <div className="mx-auto mb-3 h-8 w-8 animate-pulse rounded-full bg-gold-400/60" />')
out.append('      <p className="text-xs uppercase tracking-[0.2em] text-surface-500">Loading 3D sim...</p>')
out.append('    </div>')
out.append('  </div>')
out.append(')')
out.append('')
out.append('export const SIM_LOADERS: Record<string, React.ComponentType> = {')
for e in entries:
    imp = e['importPath'].replace('./', '')
    out.append("  '" + e['id'] + "': dynamic(() => import('@/components/simulations/three/" + imp + "'), { ssr: false, loading }),")
out.append('}')
open('app/3d-lab/simLoaders.ts', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('simLoaders.ts written')

meta = [{'id': e['id'], 'title': e['title'], 'subject': e['subject'],
         'chapter': e['chapter'], 'why3d': e['why3d']} for e in entries]
json.dump(meta, open('app/3d-lab/agentSims.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('agentSims.json written')
