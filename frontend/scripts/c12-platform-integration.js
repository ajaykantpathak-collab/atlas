// ─── 1. Generate C12 registry file ───────────────────────────
function generateRegistry() {
  console.log('Generating C12 registry...');

  const lines = [];
  lines.push("/* ═══════════════════════════════════════════════════════════════════════════");
  lines.push("   c12-registry.ts — Registry of all 173 C12 simulation components.");
  lines.push("   Auto-generated by scripts/c12-platform-integration.js");
  lines.push("   DO NOT EDIT MANUALLY — regenerate with: node scripts/c12-platform-integration.js");
  lines.push("   ═══════════════════════════════════════════════════════════════════════════ */");
  lines.push("");
  lines.push("import dynamic from 'next/dynamic'");
  lines.push("");
  lines.push("import type { GameMeta } from './gameRegistry'");
  lines.push("");

  // Dynamic imports for each template
  for (const t of PLAN) {
    const varName = t.id.replace(/C12_/g, '');
    lines.push(`const ${varName} = dynamic(() => import('@/components/simulations/c9_12/${t.id}').then(m => m.${t.id}), { ssr: false }) as unknown as React.ComponentType<{ onComplete?: (score: number) => void; width?: number; height?: number }>`);
  }

  lines.push("");
  lines.push("export const C12_GAMES: GameMeta[] = [");

  for (const t of PLAN) {
    const display = SUBJECT_DISPLAY[t.subject] || { name: t.subject, emoji: '📚', color: '#6b7280' };
    const varName = t.id.replace(/C12_/g, '');
    // Clean name from ID
    const cleanName = t.id
      .replace(/^C12_/, '')
      .replace(/Sim$/, '')
      .replace(/([A-Z])/g, ' $1')
      .trim();
    lines.push("  {");
    lines.push(`    id: '${t.id}',`);
    lines.push(`    name: '${cleanName}',`);
    lines.push(`    emoji: '${display.emoji}',`);
    lines.push(`    color: '${display.color}',`);
    lines.push(`    nodeIds: [${t.nodes.map(n => `'${n}'`).join(', ')}],`);
    lines.push(`    subject: '${t.subject}',`);
    lines.push(`    classLevel: 12,`);
    lines.push(`    component: ${varName},`);
    lines.push("  },");
  }

  lines.push("]");
  lines.push("");

  // Helper functions
  lines.push("export function getC12GameForNode(nodeId: string): GameMeta | null {");
  lines.push("  for (const game of C12_GAMES) {");
  lines.push("    if (game.nodeIds.includes(nodeId)) return game");
  lines.push("  }");
  lines.push("  return null");
  lines.push("}");
  lines.push("");
  lines.push("export function getC12GamesForSubject(subject: string): GameMeta[] {");
  lines.push("  return C12_GAMES.filter(g => g.subject === subject)");
  lines.push("}");
  lines.push("");
  lines.push("export function getAllC12Games(): GameMeta[] {");
  lines.push("  return C12_GAMES");
  lines.push("}");
  lines.push("");

  const outPath = path.join(FRONTEND_DIR, 'lib', 'c12-registry.ts');
  fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
  console.log(`  Written: ${outPath} (${lines.length} lines)`);
}

