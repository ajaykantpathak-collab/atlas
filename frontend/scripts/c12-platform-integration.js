function getPrerequisites(templateId, subject, idx, subjTemplates) {
  // Use designed prerequisites if available
  if (PREREQUISITE_MAP[subject] && PREREQUISITE_MAP[subject][templateId]) {
    return PREREQUISITE_MAP[subject][templateId];
  }
  // Fallback: no prerequisites for first in subject, none for others if not mapped
  return [];
}

function generateTopicMap() {
  console.log('Generating C12 topic map...');

  const lines = [];
  lines.push("/* ═══════════════════════════════════════════════════════════════════════════");
  lines.push("   c12-topic-map.ts — Topic map entries for all 173 C12 templates.");
  lines.push("   Each template is a topic node with prerequisites (sequential within subject).");
  lines.push("   Auto-generated by scripts/c12-platform-integration.js");
  lines.push("   DO NOT EDIT MANUALLY — regenerate with: node scripts/c12-platform-integration.js");
  lines.push("   ═══════════════════════════════════════════════════════════════════════════ */");
  lines.push("");
  lines.push("import type { TopicNode } from './game-engine/progression/TopicSelector'");
  lines.push("");

  // Group templates by subject to build prerequisites
  const bySubject = {};
  for (const t of PLAN) {
    if (!bySubject[t.subject]) bySubject[t.subject] = [];
    bySubject[t.subject].push(t);
  }

  lines.push("export const C12_TOPIC_MAP: TopicNode[] = [");

  for (const t of PLAN) {
    const display = SUBJECT_DISPLAY[t.subject] || { emoji: '📚' };
    const cleanName = t.id
      .replace(/^C12_/, '')
      .replace(/Sim$/, '')
      .replace(/([A-Z])/g, ' $1')
      .trim();

    // Prerequisite: previous template in same subject
    const subjTemplates = bySubject[t.subject];
    const idx = subjTemplates.indexOf(t);
    // Prerequisites: designed per subject, not just sequential
    const prereqs = getPrerequisites(t.id, t.subject, idx, subjTemplates);

    lines.push("  {");
    lines.push(`    id: '${t.id}',`);
    lines.push(`    name: '${cleanName}',`);
    lines.push(`    subject: '${t.subject}',`);
    lines.push(`    classLevel: 12,`);
    lines.push(`    emoji: '${display.emoji}',`);
    lines.push(`    prerequisites: [${prereqs.map(p => `'${p}'`).join(', ')}],`);
    lines.push(`    gameId: '${t.id}',`);
    lines.push("  },");
  }

  lines.push("]");
  lines.push("");

  // Helper to merge with existing topic map
  lines.push("export function getAllTopicsWithC12(): TopicNode[] {");
  lines.push("  // Import the existing C1-5 topic map at runtime");
  lines.push("  // and merge with C12 topics");
  lines.push("  return C12_TOPIC_MAP");
  lines.push("}");
  lines.push("");

  const outPath = path.join(FRONTEND_DIR, 'lib', 'c12-topic-map.ts');
  fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
  console.log(`  Written: ${outPath} (${lines.length} lines)`);
}

// ─── 3. Generate C12 misconception routing ───────────────────
function generateMisconceptionRouting() {
  console.log('Generating C12 misconception routing...');

  const routing = {};

  for (const t of PLAN) {
    const subjDir = path.join(CISCE_DIR, t.subject, 'enrichment');
    if (!fs.existsSync(subjDir)) continue;

    const enrichFiles = fs.readdirSync(subjDir)
      .filter(f => f.startsWith('c12_') && f.endsWith('.marker'))
      .sort();

    for (const file of enrichFiles) {
      const content = fs.readFileSync(path.join(subjDir, file), 'utf8');

      // Extract misconception sections per node
      for (const nodeId of t.nodes) {
        const nodeMarker = `--- NODE ${nodeId} ---`;
        const idx = content.indexOf(nodeMarker);
        if (idx === -1) continue;

        const nextNodeIdx = content.indexOf('\n--- NODE ', idx + nodeMarker.length);
        const endIdx = nextNodeIdx !== -1 ? nextNodeIdx : content.length;
        const nodeContent = content.substring(idx, endIdx);

        // Extract misconception lines
        const misconceptions = [];
        const lines = nodeContent.split('\n');
        let inMisconception = false;
        for (const line of lines) {
          if (line.toLowerCase().includes('misconception')) {
            inMisconception = true;
            misconceptions.push(line.trim());
          } else if (inMisconception && line.trim() && !line.startsWith('---')) {
            misconceptions.push(line.trim());
          } else if (inMisconception && !line.trim()) {
            inMisconception = false;
          }
        }

        if (misconceptions.length > 0) {
          if (!routing[nodeId]) routing[nodeId] = [];
          routing[nodeId].push(...misconceptions.slice(0, 5)); // max 5 per node
        }
      }
    }
  }

  const lines = [];
  lines.push("/* ═══════════════════════════════════════════════════════════════════════════");
  lines.push("   c12-misconceptions.ts — Misconception data extracted from enrichment files.");
  lines.push("   Used by RemediationManager to route wrong answers to targeted corrections.");
  lines.push("   Auto-generated by scripts/c12-platform-integration.js");
  lines.push("   DO NOT EDIT MANUALLY — regenerate with: node scripts/c12-platform-integration.js");
  lines.push("   ═══════════════════════════════════════════════════════════════════════════ */");
  lines.push("");
  lines.push("export const C12_MISCONCEPTIONS: Record<string, string[]> = {");

  for (const [nodeId, misconceptions] of Object.entries(routing)) {
    const escaped = misconceptions.map(m => `    '${m.replace(/'/g, "\\'")}'`).join(',\n');
    lines.push(`  '${nodeId}': [`);
    lines.push(escaped);
    lines.push("  ],");
  }

  lines.push("}");
  lines.push("");
  lines.push("export function getMisconceptionsForNode(nodeId: string): string[] {");
  lines.push("  return C12_MISCONCEPTIONS[nodeId] || []");
  lines.push("}");
  lines.push("");

  const outPath = path.join(FRONTEND_DIR, 'lib', 'c12-misconceptions.ts');
  fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
  const nodeCount = Object.keys(routing).length;
  console.log(`  Written: ${outPath} (${nodeCount} nodes with misconceptions, ${lines.length} lines)`);
}

