"""Neo4j loader — reads atomic_graph JSON files and loads them into Neo4j.

Reads from:
  - D:/node_generator/atomic_graph/*.json (CBSE, 6167 nodes)
  - D:/node_generator/atomic_graph/cisce/*.json (CISCE, generated by subagents)

Creates:
  - KnowledgeNode nodes with all properties
  - REQUIRES edges with reason property (prerequisite links)
  - UNLOCKS edges with reason property (forward links)
  - Subject and Chapter nodes for organization

Usage:
    python -m backend.database.neo4j_loader
    python -m backend.database.neo4j_loader --board CBSE
    python -m backend.database.neo4j_loader --board CISCE
    python -m backend.database.neo4j_loader --dry-run
"""

import argparse
import asyncio
import json
import os
from pathlib import Path
from typing import Any, Optional

from neo4j import AsyncGraphDatabase

# Read settings directly to avoid importing backend.database (which pulls SQLAlchemy)
