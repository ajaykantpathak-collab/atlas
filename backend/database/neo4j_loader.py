NEO4J_URI = os.environ.get("NEO4J_URI", "bolt://localhost:7687")
NEO4J_USER = os.environ.get("NEO4J_USER", "neo4j")
NEO4J_PASSWORD = os.environ.get("NEO4J_PASSWORD", "dream_neo4j_2024")

CBSE_ATOMIC_DIR = Path("D:/node_generator/atomic_graph")
CISCE_ATOMIC_DIR = Path("D:/node_generator/atomic_graph/cisce_enriched")


def load_json_files(directory: Path, board: str) -> list[dict[str, Any]]:
    """Load all JSON files from a directory, returning a list of nodes."""
    all_nodes = []
    if not directory.exists():
        print(f"  WARNING: Directory not found: {directory}")
        return all_nodes

    for json_file in sorted(directory.glob("*.json")):
        # Skip v2 files — they duplicate node_ids from v1 with fewer nodes
        if "_v2" in json_file.name:
            print(f"  SKIP (v2 duplicate): {json_file.name}")
            continue
        try:
            with open(json_file, "r", encoding="utf-8") as f:
                data = json.load(f)
            if isinstance(data, list):
                for node in data:
                    node["_board"] = board
                    node["_source_file"] = json_file.name
                all_nodes.extend(data)
                print(f"  Loaded {len(data):4d} nodes from {json_file.name}")
        except (json.JSONDecodeError, Exception) as e:
            print(f"  ERROR reading {json_file.name}: {e}")
    return all_nodes


async def clear_graph(driver, board: Optional[str] = None):
    """Clear existing nodes. If board specified, only clear that board's nodes."""
    async with driver.session() as session:
        if board:
            print(f"  Clearing existing {board} nodes and edges...")
            await session.run(
                "MATCH (n:KnowledgeNode {board: $board}) "
                "DETACH DELETE n",
                board=board,
            )
        else:
            print("  Clearing ALL nodes and edges...")
            await session.run("MATCH (n) DETACH DELETE n")


async def create_subjects_and_chapters(driver, nodes: list[dict]):
    """Create Subject and Chapter nodes for organization."""
    subjects_seen = set()
    chapters_seen = set()

    for node in nodes:
        board = node.get("_board", "CBSE")
        subject = node.get("subject", "unknown")
        class_level = node.get("class", 0)
        chapter_name = node.get("chapter_name", "")
        chapter = node.get("chapter", "")

        subj_key = f"{board}_{class_level}_{subject}"
        if subj_key not in subjects_seen:
            subjects_seen.add(subj_key)
            async with driver.session() as session:
                await session.run(
                    "MERGE (s:Subject {subject_key: $key}) "
                    "SET s.board = $board, s.class_level = $cls, "
                    "    s.subject = $subj",
                    key=subj_key, board=board, cls=class_level, subj=subject,
                )

        chap_key = f"{board}_{class_level}_{subject}_{chapter}"
        if chap_key not in chapters_seen and chapter_name:
            chapters_seen.add(chap_key)
            async with driver.session() as session:
                await session.run(
                    "MERGE (c:Chapter {chapter_key: $key}) "
                    "SET c.board = $board, c.class_level = $cls, "
                    "    c.subject = $subj, c.chapter = $chap, "
                    "    c.chapter_name = $chap_name",
                    key=chap_key, board=board, cls=class_level,
                    subj=subject, chap=chapter, chap_name=chapter_name,
                )


async def load_nodes_batch(driver, nodes: list[dict], batch_size: int = 500):
    """Load nodes into Neo4j in batches using UNWIND."""
    total = len(nodes)
    loaded = 0

    for i in range(0, total, batch_size):
        batch = nodes[i : i + batch_size]
        params = []
        for node in batch:
            params.append({
                "node_id": node.get("node_id", ""),
                "topic": node.get("topic", ""),
                "chapter": node.get("chapter", ""),
                "chapter_name": node.get("chapter_name", ""),
                "class_level": node.get("class", 0),
                "subject": node.get("subject", ""),
                "board": node.get("_board", "CBSE"),
                "concept_tags": json.dumps(node.get("concept_tags", [])),
                "content_snippet": node.get("content_snippet", ""),
                "scope_constraints": json.dumps(node.get("scope_constraints", [])),
                "prerequisite_node_ids": node.get("prerequisite_node_ids", []),
                "prerequisite_reasons": json.dumps(node.get("prerequisite_reasons", {})),
                "forward_node_ids": node.get("forward_node_ids", []),
                "forward_reasons": json.dumps(node.get("forward_reasons", {})),
                "cross_subject_prereqs": node.get("cross_subject_prereqs", []),
                "cross_subject_reasons": json.dumps(node.get("cross_subject_reasons", {})),
                "is_root": node.get("is_root", False),
                "difficulty": node.get("difficulty_level", "medium"),
                "estimated_time": node.get("estimated_learning_minutes", 30),
                "source_file": node.get("_source_file", ""),
            })

        async with driver.session() as session:
            await session.run(
                """
                UNWIND $nodes AS node
                MERGE (n:KnowledgeNode {node_id: node.node_id})
                SET n.topic = node.topic,
                    n.chapter = node.chapter,
                    n.chapter_name = node.chapter_name,
                    n.class_level = node.class_level,
                    n.subject = node.subject,
                    n.board = node.board,
                    n.concept_tags = node.concept_tags,
                    n.content_snippet = node.content_snippet,
                    n.scope_constraints = node.scope_constraints,
                    n.prerequisite_node_ids = node.prerequisite_node_ids,
                    n.prerequisite_reasons = node.prerequisite_reasons,
                    n.forward_node_ids = node.forward_node_ids,
                    n.forward_reasons = node.forward_reasons,
                    n.cross_subject_prereqs = node.cross_subject_prereqs,
                    n.cross_subject_reasons = node.cross_subject_reasons,
                    n.is_root = node.is_root,
                    n.difficulty = node.difficulty,
                    n.estimated_time = node.estimated_time,
                    n.source_file = node.source_file
                """,
                nodes=params,
            )
        loaded += len(batch)
        print(f"  Loaded {loaded}/{total} nodes...")

    return loaded


async def create_edges_batch(driver, nodes: list[dict]):
    """Create REQUIRES, UNLOCKS, and RELATED_TO edges from JSON node data."""
    requires_edges = []
    unlocks_edges = []
    related_edges = []

    for node in nodes:
        node_id = node.get("node_id", "")
        prereq_reasons = node.get("prerequisite_reasons", {})
        forward_reasons = node.get("forward_reasons", {})
        related_reasons = node.get("related_reasons", {})
        cross_reasons = node.get("cross_subject_reasons", {})

        for prereq_id in node.get("prerequisite_node_ids", []):
            reason = prereq_reasons.get(prereq_id, "") if isinstance(prereq_reasons, dict) else ""
            requires_edges.append({
                "source": node_id,
                "target": prereq_id,
                "reason": reason,
            })

        for forward_id in node.get("forward_node_ids", []):
            reason = forward_reasons.get(forward_id, "") if isinstance(forward_reasons, dict) else ""
            unlocks_edges.append({
                "source": node_id,
                "target": forward_id,
                "reason": reason,
            })

        for related_id in node.get("related_node_ids", []):
            reason = related_reasons.get(related_id, "") if isinstance(related_reasons, dict) else ""
            related_edges.append({
                "source": node_id,
                "target": related_id,
                "reason": reason,
            })

        # Cross-subject prerequisites → RELATED_TO edges with cross_subject=true
        for cross_id in node.get("cross_subject_prereqs", []):
            reason = cross_reasons.get(cross_id, "") if isinstance(cross_reasons, dict) else ""
            related_edges.append({
                "source": node_id,
                "target": cross_id,
                "reason": f"[CROSS-SUBJECT] {reason}",
            })

    print(f"  Creating {len(requires_edges)} REQUIRES edges...")
    print(f"  Creating {len(unlocks_edges)} UNLOCKS edges...")
    print(f"  Creating {len(related_edges)} RELATED_TO edges (incl. cross-subject)...")

    # Create REQUIRES edges in batches
    for i in range(0, len(requires_edges), 500):
        batch = requires_edges[i : i + 500]
        async with driver.session() as session:
            await session.run(
                """
                UNWIND $edges AS edge
                MATCH (n:KnowledgeNode {node_id: edge.source})
                MATCH (m:KnowledgeNode {node_id: edge.target})
                MERGE (n)-[r:REQUIRES]->(m)
                SET r.reason = edge.reason
                """,
                edges=batch,
            )

    # Create UNLOCKS edges in batches
    for i in range(0, len(unlocks_edges), 500):
        batch = unlocks_edges[i : i + 500]
        async with driver.session() as session:
            await session.run(
                """
                UNWIND $edges AS edge
                MATCH (n:KnowledgeNode {node_id: edge.source})
                MATCH (m:KnowledgeNode {node_id: edge.target})
                MERGE (n)-[r:UNLOCKS]->(m)
                SET r.reason = edge.reason
                """,
                edges=batch,
            )

    # Create RELATED_TO edges in batches
    for i in range(0, len(related_edges), 500):
        batch = related_edges[i : i + 500]
        async with driver.session() as session:
            await session.run(
                """
                UNWIND $edges AS edge
                MATCH (n:KnowledgeNode {node_id: edge.source})
                MATCH (m:KnowledgeNode {node_id: edge.target})
                MERGE (n)-[r:RELATED_TO]->(m)
                SET r.reason = edge.reason
                """,
                edges=batch,
            )

    return len(requires_edges), len(unlocks_edges), len(related_edges)


async def verify_graph(driver) -> dict:
    """Verify the loaded graph — count nodes, edges, check for orphans."""
    async with driver.session() as session:
        node_result = await session.run(
            "MATCH (n:KnowledgeNode) RETURN count(n) AS count"
        )
        node_count = (await node_result.single())["count"]

        edge_result = await session.run(
            "MATCH ()-[r:REQUIRES]->() RETURN count(r) AS count"
        )
        edge_count = (await edge_result.single())["count"]

        unlock_result = await session.run(
            "MATCH ()-[r:UNLOCKS]->() RETURN count(r) AS count"
        )
        unlock_count = (await unlock_result.single())["count"]

        related_result = await session.run(
            "MATCH ()-[r:RELATED_TO]->() RETURN count(r) AS count"
        )
        related_count = (await related_result.single())["count"]

        board_result = await session.run(
            "MATCH (n:KnowledgeNode) RETURN n.board AS board, count(n) AS count "
            "ORDER BY board"
        )
        board_counts = [(r["board"], r["count"]) async for r in board_result]

        orphan_result = await session.run(
            "MATCH (n:KnowledgeNode) "
            "WHERE NOT (n)-[:REQUIRES]->() AND NOT ()-[:REQUIRES]->(n) "
            "RETURN count(n) AS count"
        )
        orphan_count = (await orphan_result.single())["count"]

        root_result = await session.run(
            "MATCH (n:KnowledgeNode {is_root: true}) RETURN count(n) AS count"
        )
        root_count = (await root_result.single())["count"]

    return {
        "total_nodes": node_count,
        "total_edges": edge_count,
        "unlock_edges": unlock_count,
        "related_edges": related_count,
        "boards": board_counts,
        "orphan_nodes": orphan_count,
        "root_nodes": root_count,
    }


async def main(board_filter: Optional[str] = None, dry_run: bool = False):
    print("=" * 60)
    print("Neo4j Knowledge Graph Loader")
    print("=" * 60)

    # Step 1: Load JSON files
    print("\n[1/5] Loading JSON files...")
    all_nodes = []
    if board_filter is None or board_filter == "CBSE":
        print("  Loading CBSE atomic graph...")
        all_nodes.extend(load_json_files(CBSE_ATOMIC_DIR, "CBSE"))
    if board_filter is None or board_filter == "CISCE":
        print("  Loading CISCE atomic graph...")
        all_nodes.extend(load_json_files(CISCE_ATOMIC_DIR, "CISCE"))

    print(f"\n  Total nodes loaded from JSON: {len(all_nodes)}")

    if dry_run:
        print("\n[DRY RUN] Skipping Neo4j operations.")
        boards = {}
        for n in all_nodes:
            b = n.get("_board", "unknown")
            boards[b] = boards.get(b, 0) + 1
        for b, c in sorted(boards.items()):
            print(f"    {b}: {c} nodes")
        return

    # Step 2: Connect to Neo4j
    print("\n[2/5] Connecting to Neo4j...")
    driver = AsyncGraphDatabase.driver(
        NEO4J_URI,
        auth=(NEO4J_USER, NEO4J_PASSWORD),
    )

    try:
        # Step 3: Clear existing data
        print("\n[3/5] Clearing existing graph...")
        await clear_graph(driver, board_filter)

        # Step 4: Load nodes and edges
        print("\n[4/5] Loading nodes into Neo4j...")
        loaded = await load_nodes_batch(driver, all_nodes)
        print(f"  Loaded {loaded} nodes.")

        print("\n  Creating subjects and chapters...")
        await create_subjects_and_chapters(driver, all_nodes)

        print("\n  Creating edges...")
        req_count, unlock_count, related_count = await create_edges_batch(driver, all_nodes)
        print(f"  Created {req_count} REQUIRES edges, {unlock_count} UNLOCKS edges, {related_count} RELATED_TO edges.")

        # Step 5: Verify
        print("\n[5/5] Verifying graph...")
        stats = await verify_graph(driver)
        print(f"\n  Total nodes:     {stats['total_nodes']}")
        print(f"  REQUIRES edges:  {stats['total_edges']}")
        print(f"  UNLOCKS edges:   {stats['unlock_edges']}")
        print(f"  RELATED_TO edges:{stats['related_edges']}")
        print(f"  Root nodes:      {stats['root_nodes']}")
        print(f"  Orphan nodes:    {stats['orphan_nodes']}")
        print(f"\n  By board:")
        for board, count in stats["boards"]:
            print(f"    {board}: {count} nodes")

        print("\n" + "=" * 60)
        print("Graph loaded successfully!")
        print("=" * 60)

    finally:
        await driver.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Load atomic graph into Neo4j")
    parser.add_argument("--board", choices=["CBSE", "CISCE"], help="Load only one board")
    parser.add_argument("--dry-run", action="store_true", help="Don't write to Neo4j")
    args = parser.parse_args()
    asyncio.run(main(board_filter=args.board, dry_run=args.dry_run))
