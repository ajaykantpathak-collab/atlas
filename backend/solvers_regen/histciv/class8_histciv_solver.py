def make_seed(*args) -> int:
    """Deterministic integer seed from any number of arguments."""
    raw = json.dumps(args, sort_keys=True, default=str)
    h = hashlib.md5(raw.encode()).hexdigest()
    return int(h, 16) % (2**31)


def normalize(s: str) -> str:
    """Normalise whitespace and case for comparison."""
    return " ".join(s.lower().split())


def kw_score(user: str, keywords: List[str]) -> float:
    """Return fraction of required keywords found in user answer (0.0-1.0)."""
    un = normalize(user)
    found = sum(1 for k in keywords if k.lower() in un)
    return found / len(keywords) if keywords else 0.0


def shuffle_deterministic(seed: int, items: List[Any]) -> List[Any]:
    """Return a shuffled copy of items using a fixed seed."""
    r = random.Random(seed)
    result = list(items)
    r.shuffle(result)
    return result


