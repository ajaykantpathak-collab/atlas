import urllib.request, json, ssl, time

ctx = ssl.create_default_context()
KEY = '93296b71324642388f2a0023c9b49305.ToP65AZkwP2OnUiZ'
BASE = 'https://open.bigmodel.cn/api/paas/v4'

# Read a Claude-generated example to show GLM what quality we expect
example = open(r'D:\platform\parsed_output\english_granular_nodes\c11_eng_102_subnodes.json', encoding='utf-8').read()
import json as j
example_data = j.loads(example)
example_node = example_data['sub_nodes'][0]

example_text = f"""Here is an EXAMPLE of the quality we expect (generated by Claude Opus):

TITLE: {example_node['title']}
NODE_TYPE: {example_node['node_type']}
CONTENT: {example_node['content'][:1500]}
MASTERY_CRITERIA: {example_node['mastery_criteria'][:300]}
DIAGNOSTIC_QUESTIONS: {len(example_node['diagnostic_questions'])} questions across multiple levels
MISCONCEPTIONS: {len(example_node['common_misconceptions'])} detailed misconceptions with corrections

Now generate content of THIS quality and depth. Match the analytical depth, the exam focus, and the specific textual references."""

system_prompt = """You are a master English teacher and CISCE/ISC curriculum expert. You generate world-class learning content for Indian students preparing for ICSE/ISC exams.

Your content must be:
- Analytically deep (not superficial summaries)
- Exam-focused (directly useful for board exam answers)
- Textually accurate (real quotes, correct act/scene references)
- Rich in literary analysis (character arcs, themes, devices, structure)
- Include diagnostic questions at multiple Bloom's levels
- Include common misconceptions with specific corrections

You write at the level of a senior English teacher with 20+ years of ISC exam preparation experience."""

prompt = f"""Create a QUOTE BANK for "Julius Caesar Act I" by William Shakespeare (Class 9, CISCE English Literature).

{example_text}

For EACH important quote, provide:
- The exact quote (accurate to Shakespeare's text)
- Speaker
- Context (act, scene, situation)
- Literal meaning
- What it reveals about character/theme
- Themes it connects to
- Exam questions it answers

Include 15-20 quotes. Use this format:

<<<QUOTE>>>
QUOTE: (exact quote)
SPEAKER: (who said it)
CONTEXT: (when/where)
LITERAL_MEANING: (what it means)
REVEALS: (what it reveals)
THEMES: (comma-separated)
EXAM_USE: (which exam questions this answers)
<<<END>>>

Write ALL quotes. No JSON."""

url = f'{BASE}/chat/completions'
body = json.dumps({
    'model': 'glm-4-flash',
    'messages': [
        {'role': 'system', 'content': system_prompt},
        {'role': 'user', 'content': prompt},
    ],
    'max_tokens': 8000,
    'temperature': 0.7,
}).encode()

req = urllib.request.Request(url, data=body, method='POST')
req.add_header('Authorization', 'Bearer ' + KEY)
req.add_header('Content-Type', 'application/json')

start = time.time()
with urllib.request.urlopen(req, timeout=180, context=ctx) as resp:
    data = json.loads(resp.read().decode())
    elapsed = time.time() - start
    text = data.get('choices', [{}])[0].get('message', {}).get('content', '')
    usage = data.get('usage', {})
    print('Model: glm-4-flash')
    print('Response time: %.1fs' % elapsed)
    print('Tokens in: %s, out: %s' % (usage.get('prompt_tokens'), usage.get('completion_tokens')))
    print('Content length: %d chars (%.1f KB)' % (len(text), len(text)/1024))
    print('Quotes found: %d' % text.count('<<<QUOTE>>>'))
    print()
    print('=== FIRST 2500 CHARS ===')
    print(text[:2500])
    print()
    print('=== LAST 500 CHARS ===')
    print(text[-500:])
