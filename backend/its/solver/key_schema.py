"""key_schema.py -- Key Schema and KeyGrid for the ITS assessment grid.

A "key" is the atomic unit of assessment: one Learning Outcome x one
Cognitive Move. Each key carries everything needed to generate, serve and
assess questions: the reasoning pattern the student should follow, the
mark split per step, the curriculum graph nodes it draws from, the
prerequisite keys that must be mastered first, the misconceptions to watch
for, the context families allowed in word problems, and the difficulty
range the generated questions may span.

Everything here is deterministic -- no LLM calls. Learning outcomes are
derived mechanically from node ``scope_constraints`` (positive constraints
become outcomes, "Skip ..." constraints are excluded), and keys are
generated by crossing outcomes with a fixed list of cognitive moves.

Usage::

    from backend.its.solver.key_schema import KeyGrid

    grid = KeyGrid()
    grid.load_from_graph("cbse_data/nodes/by_class/split/final_repaired")
    grid.generate_keys(min_per_chapter=3)
    report = grid.coverage_report()
    grid.save("out/key_grid.json")
"""

from __future__ import annotations

import copy
import hashlib
import json
import logging
import os
import re
from typing import Any, Dict, List, Optional, Tuple

logger = logging.getLogger(__name__)

GRID_FORMAT = "key_grid_v1"

# --------------------------------------------------------------------------- #
# Vocabulary
# --------------------------------------------------------------------------- #

COGNITIVE_MOVES: List[str] = [
    "apply",
    "analyse",
    "evaluate",
    "compare",
    "interpret_data",
]

CONTEXT_FAMILIES: List[str] = [
    "home",
    "sport",
    "industry",
    "commerce",
    "nature",
    "data",
]

# Deterministic reasoning patterns per cognitive move (3-5 steps each).
REASONING_PATTERNS: Dict[str, List[str]] = {
    "apply": [
        "identify the given quantities and what is asked",
        "select the method or formula that fits the problem type",
        "carry out the steps in order",
        "check the result against the context",
    ],
    "analyse": [
        "break the situation into its components",
        "identify the relationships between the components",
        "reason through the relationships to the required conclusion",
        "state the conclusion precisely",
    ],
    "evaluate": [
        "state the criterion or rule being judged against",
        "gather evidence relevant to the criterion",
        "apply the criterion to the evidence",
        "justify the judgement",
    ],
    "compare": [
        "identify the attributes to compare",
        "examine each case on each attribute",
        "record the similarities and the differences",
        "state which case satisfies the given condition",
    ],
    "interpret_data": [
        "read the relevant values from the data",
        "choose the operation or transformation needed",
        "compute the derived quantity",
        "state what the number means in context",
    ],
}

# Mark split per step -- exactly one entry per reasoning step.
MARKING_TEMPLATES: Dict[str, List[str]] = {
    "apply": [
        "M1: setup -- given/required identified (1 mark)",
        "M2: method chosen (1 mark)",
        "M3: steps executed correctly (1 mark)",
        "A1: final answer with units (1 mark)",
    ],
    "analyse": [
        "M1: components identified (1 mark)",
        "M2: relationships identified (1 mark)",
        "M3: reasoning through to the conclusion (1 mark)",
        "C1: conclusion stated precisely (1 mark)",
    ],
    "evaluate": [
        "M1: criterion stated (1 mark)",
        "E1: evidence gathered (1 mark)",
        "M2: criterion applied to the evidence (1 mark)",
        "J1: justified judgement (1 mark)",
    ],
    "compare": [
        "M1: attributes identified (1 mark)",
        "M2: cases examined attribute-wise (1 mark)",
        "C1: similarities and differences recorded (1 mark)",
        "C2: condition matched to a case (1 mark)",
    ],
    "interpret_data": [
        "R1: values read correctly (1 mark)",
        "T1: transformation chosen (1 mark)",
        "C1: computation carried out (1 mark)",
        "I1: inference stated in context (1 mark)",
    ],
}

CONTEXT_FAMILIES_BY_MOVE: Dict[str, List[str]] = {
    "apply": ["home", "sport"],
    "analyse": ["industry", "nature"],
    "evaluate": ["commerce", "industry"],
    "compare": ["nature", "home"],
    "interpret_data": ["data"],
}

# --------------------------------------------------------------------------- #
# KEY_SCHEMA template
# --------------------------------------------------------------------------- #

#: Template showing every field of a key. Use :func:`make_key` to build a
#: concrete key with fresh (non-shared) list values.
KEY_SCHEMA: Dict[str, Any] = {
    "key_id": "",                # e.g. "maths_c10_quadratic_apply"
    "subject": "",               # normalised, e.g. "maths"
    "class_level": 0,            # 6..12
    "chapter": "",               # chapter name from the node graph
    "topic": "",                 # topic of the source node
    "learning_outcome": "",      # "Students can solve quadratic equations by factorisation"
    "cognitive_move": "",        # one of COGNITIVE_MOVES
    "reasoning_pattern": [],     # 3-5 steps
    "marking_template": [],      # mark split per step
    "node_ids": [],              # linked curriculum graph nodes
    "prerequisite_keys": [],     # keys that must be mastered first
    "misconceptions": [],        # [{"id", "description", "node_id"}]
    "context_families": [],      # subset of CONTEXT_FAMILIES
    "difficulty_range": [1, 3],  # inclusive [low, high]
}

KEY_FIELDS = frozenset(KEY_SCHEMA)

# Scope constraints starting with these lead words are exclusions, not
# outcomes.
_SKIP_PREFIXES = (
    "skip",
    "avoid",
    "exclude",
    "omit",
    "ignore",
    "do not",
    "don't",
    "dont",
    "no need",
    "beyond scope",
)

# Positive constraint lead verb -> outcome verb.
_LEAD_VERBS = {
    "teach": "explain",
    "include": "explain",
    "emphasise": "explain",
    "emphasize": "explain",
    "highlight": "explain",
    "focus": "explain",
    "cover": "explain",
    "introduce": "describe",
    "explore": "describe",
    "derive": "derive",
    "apply": "apply",
    "use": "apply",
    "develop": "construct",
    "build": "construct",
    "demonstrate": "demonstrate",
    "show": "demonstrate",
    "practise": "practise",
    "practice": "practise",
}

_SUBJECT_ALIASES = {
    "math": "maths",
    "mathematics": "maths",
    "maths": "maths",
}


# --------------------------------------------------------------------------- #
# Small deterministic helpers
# --------------------------------------------------------------------------- #

def slugify(text: str, max_len: int = 48) -> str:
    """Lowercase ASCII slug: 'Real Numbers (Class 10)' -> 'real_numbers_class_10'."""
    s = re.sub(r"[^a-z0-9]+", "_", str(text).lower()).strip("_")
    s = s[:max_len].rstrip("_")
    return s or "na"


def chapter_slug(chapter: str, max_len: int = 48) -> str:
    """Slug for a chapter that stays collision-free when truncated.

    Long chapter names are trimmed and suffixed with a short deterministic
    hash so '... Techniques Part 1' and '... Techniques Part 2' never share
    a key-id base.
    """
    full = slugify(chapter, max_len=10_000)
    if len(full) <= max_len:
        return full
    digest = hashlib.md5(str(chapter).encode("utf-8")).hexdigest()[:8]
    return "%s_%s" % (slugify(chapter, max_len=max_len - 9), digest)


def normalize_subject(subject: str) -> str:
    """Normalise a subject label: 'Mathematics' -> 'maths', 'English Lit' style
    multi-word subjects become snake_case."""
    s = re.sub(r"[\s\-]+", "_", str(subject).strip().lower())
    s = re.sub(r"_+", "_", s).strip("_")
    return _SUBJECT_ALIASES.get(s, s)


def _to_int(value: Any) -> Optional[int]:
    """Best-effort int coercion ('class_10' -> 10)."""
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value
    m = re.search(r"\d+", str(value))
    return int(m.group()) if m else None


def make_key(**overrides: Any) -> Dict[str, Any]:
    """Build a concrete key dict from the KEY_SCHEMA template.

    Raises ValueError on an unknown cognitive move or an unknown field.
    """
    key = copy.deepcopy(KEY_SCHEMA)
    for field, value in overrides.items():
        if field not in KEY_FIELDS:
            raise ValueError("unknown key field: %s" % field)
        key[field] = copy.deepcopy(value)
    if key["cognitive_move"] and key["cognitive_move"] not in COGNITIVE_MOVES:
        raise ValueError(
            "cognitive_move must be one of %s, got %r"
            % (COGNITIVE_MOVES, key["cognitive_move"])
        )
    return key


def validate_key(key: Dict[str, Any]) -> List[str]:
    """Return a list of structural problems with a key dict (empty = valid)."""
    problems: List[str] = []
    missing = [f for f in KEY_FIELDS if f not in key]
    if missing:
        problems.append("missing fields: %s" % sorted(missing))
    if not key.get("key_id"):
        problems.append("key_id is empty")
    if key.get("cognitive_move") not in COGNITIVE_MOVES:
        problems.append("cognitive_move invalid: %r" % key.get("cognitive_move"))
    rp = key.get("reasoning_pattern") or []
    if not (3 <= len(rp) <= 5):
        problems.append("reasoning_pattern must have 3-5 steps, got %d" % len(rp))
    mt = key.get("marking_template") or []
    if len(mt) != len(rp):
        problems.append(
            "marking_template length %d != reasoning_pattern length %d"
            % (len(mt), len(rp))
        )
    for fam in key.get("context_families") or []:
        if fam not in CONTEXT_FAMILIES:
            problems.append("unknown context family: %r" % fam)
    dr = key.get("difficulty_range") or []
    if len(dr) != 2 or not (1 <= dr[0] <= dr[1] <= 5):
        problems.append("difficulty_range must be [low, high] within 1..5")
    return problems


def _difficulty_range(class_level: int) -> List[int]:
    if class_level <= 8:
        return [1, 3]
    if class_level <= 10:
        return [1, 4]
    return [2, 5]


def derive_outcome(constraint: str, topic: str = "") -> Optional[str]:
    """Turn one scope constraint into a learning outcome.

    Returns None for exclusion constraints ("Skip the formal proof ...").
    Deterministic: leading positive verb is mapped to an outcome verb.
    """
    s = " ".join(str(constraint).split())
    if not s:
        return None
    lower = s.lower()
    if any(lower.startswith(p) for p in _SKIP_PREFIXES):
        return None
    first, _, rest = s.partition(" ")
    verb = _LEAD_VERBS.get(first.lower())
    if verb and rest:
        return "Students can %s %s" % (verb, rest)
    return "Students can %s" % _lower_first(s)


def _lower_first(s: str) -> str:
    return s[0].lower() + s[1:] if s and s[0].isupper() else s


def _extract_nodes(data: Any) -> List[Dict[str, Any]]:
    """Pull node dicts out of an arbitrary JSON payload shape."""
    if isinstance(data, list):
        return [n for n in data if isinstance(n, dict) and n.get("node_id")]
    if isinstance(data, dict):
        if data.get("node_id"):
            return [data]
        for field in ("nodes", "data", "items", "records"):
            value = data.get(field)
            if isinstance(value, list):
                return [n for n in value if isinstance(n, dict) and n.get("node_id")]
    return []


# --------------------------------------------------------------------------- #
# KeyGrid
# --------------------------------------------------------------------------- #

class KeyGrid:
    """Grid of assessment keys built from the repaired curriculum node graph."""

    def __init__(self) -> None:
        self._keys: Dict[str, Dict[str, Any]] = {}
        self._nodes: Dict[str, Dict[str, Any]] = {}
        self._prereq_graph: Dict[str, List[str]] = {}
        self._chapter_outcomes: Dict[Tuple[str, int, str], List[Dict[str, Any]]] = {}
        self._concept_index: Dict[str, set] = {}
        self.skipped_files: List[str] = []

    # -- loading ----------------------------------------------------------- #

    def load_from_graph(self, nodes_dir: str) -> int:
        """Read every ``*.json`` file under ``nodes_dir`` and map each node's
        topic + concept_tags + scope_constraints to learning outcomes.

        Returns the number of node records loaded (deduplicated by node_id).
        Malformed files are skipped and recorded in ``self.skipped_files``.
        """
        self._nodes = {}
        self._prereq_graph = {}
        self._chapter_outcomes = {}
        self._concept_index = {}
        self._keys = {}
        self.skipped_files = []

        files: List[str] = []
        for root, _dirs, names in os.walk(nodes_dir):
            for name in sorted(names):
                if name.lower().endswith(".json"):
                    files.append(os.path.join(root, name))
        for path in sorted(files):
            try:
                with open(path, "r", encoding="utf-8") as fh:
                    data = json.load(fh)
            except (OSError, ValueError) as exc:
                logger.warning("skipping unreadable node file %s: %s", path, exc)
                self.skipped_files.append(path)
                continue
            for node in _extract_nodes(data):
                self._add_node(node)
        return len(self._nodes)

    def _add_node(self, node: Dict[str, Any]) -> None:
        node_id = str(node["node_id"])
        class_level = _to_int(node.get("class_level"))
        if class_level is None:
            return
        topic = str(node.get("topic") or node_id)
        chapter = str(node.get("chapter") or node.get("chapter_name") or topic)
        subject = normalize_subject(node.get("subject") or "unknown")

        self._nodes[node_id] = {
            "node_id": node_id,
            "topic": topic,
            "subject": subject,
            "class_level": class_level,
            "chapter": chapter,
            "concept_tags": [str(t) for t in (node.get("concept_tags") or [])],
            "scope_constraints": [str(c) for c in (node.get("scope_constraints") or [])],
        }
        self._prereq_graph[node_id] = [
            str(p) for p in (node.get("prerequisite_node_ids") or [])
        ]

        group = (subject, class_level, chapter)
        outcomes = self._chapter_outcomes.setdefault(group, [])
        constraints = self._nodes[node_id]["scope_constraints"]
        derived: List[str] = []
        for constraint in constraints:
            outcome = derive_outcome(constraint, topic)
            if outcome:
                derived.append(outcome)
        if not derived:
            derived = ["Students can explain %s" % _lower_first(topic)]
        for outcome in derived:
            norm = " ".join(outcome.lower().split())
            for existing in outcomes:
                if " ".join(existing["outcome"].lower().split()) == norm:
                    if node_id not in existing["node_ids"]:
                        existing["node_ids"].append(node_id)
                    break
            else:
                outcomes.append(
                    {"outcome": outcome, "node_ids": [node_id], "topic": topic}
                )

    # -- key generation ----------------------------------------------------- #

    def generate_keys(self, min_per_chapter: int = 3,
                      catalog: Any = None) -> int:
        """Cross learning outcomes with cognitive moves to fill the grid.

        Each chapter gets ``max(min_per_chapter, len(outcomes))`` keys,
        assigned round-robin so every outcome is covered at least once and
        every generated key maps to exactly one outcome x move pair.
        Pass a ``MisconceptionCatalog`` to auto-attach matching misconceptions.
        Returns the total number of keys in the grid.
        """
        if not self._chapter_outcomes:
            raise RuntimeError("no chapters loaded -- call load_from_graph first")
        self._keys = {}
        for (subject, class_level, chapter), outcomes in sorted(
            self._chapter_outcomes.items()
        ):
            ordered = sorted(outcomes, key=lambda o: (o["outcome"], o["node_ids"]))
            total = max(int(min_per_chapter), len(ordered))
            used_base: Dict[str, int] = {}
            for i in range(total):
                outcome_rec = ordered[i % len(ordered)]
                move = COGNITIVE_MOVES[i % len(COGNITIVE_MOVES)]
                base = "%s_c%d_%s_%s" % (
                    subject, class_level, chapter_slug(chapter), slugify(move)
                )
                n = used_base.get(base, 0) + 1
                used_base[base] = n
                key_id = base if n == 1 else "%s_%d" % (base, n)
                self._keys[key_id] = make_key(
                    key_id=key_id,
                    subject=subject,
                    class_level=class_level,
                    chapter=chapter,
                    topic=outcome_rec["topic"],
                    learning_outcome=outcome_rec["outcome"],
                    cognitive_move=move,
                    reasoning_pattern=list(REASONING_PATTERNS[move]),
                    marking_template=list(MARKING_TEMPLATES[move]),
                    node_ids=list(outcome_rec["node_ids"]),
                    prerequisite_keys=[],
                    misconceptions=[],
                    context_families=list(CONTEXT_FAMILIES_BY_MOVE[move]),
                    difficulty_range=list(_difficulty_range(class_level)),
                )
        self._wire_prerequisites()
        self._build_concept_index()
        if catalog is not None:
            self._attach_misconceptions(catalog)
        return len(self._keys)

    def _wire_prerequisites(self) -> None:
        """Fill each key's prerequisite_keys from the node prerequisite graph."""
        node_to_keys: Dict[str, List[str]] = {}
        for key_id, key in self._keys.items():
            for node_id in key["node_ids"]:
                node_to_keys.setdefault(node_id, []).append(key_id)
        for key in self._keys.values():
            prereq_nodes = {
                p
                for node_id in key["node_ids"]
                for p in self._prereq_graph.get(node_id, [])
            }
            prereq_keys = sorted(
                {
                    other
                    for node_id in prereq_nodes
                    for other in node_to_keys.get(node_id, [])
                    if other != key["key_id"]
                }
            )
            key["prerequisite_keys"] = prereq_keys

    def _build_concept_index(self) -> None:
        self._concept_index = {}
        for key_id, key in self._keys.items():
            for node_id in key["node_ids"]:
                node = self._nodes.get(node_id)
                if not node:
                    continue
                for tag in node["concept_tags"]:
                    self._concept_index.setdefault(str(tag).lower(), set()).add(key_id)

    def _attach_misconceptions(self, catalog: Any) -> None:
        for key in self._keys.values():
            attached = 0
            for entry in catalog.entries():
                if attached >= 3:
                    break
                if (
                    key["subject"] in entry["subjects"]
                    and key["class_level"] in entry["classes"]
                ):
                    key["misconceptions"].append(
                        {
                            "id": entry["id"],
                            "description": entry["description"],
                            "node_id": key["node_ids"][0] if key["node_ids"] else "",
                        }
                    )
                    attached += 1

    # -- queries ------------------------------------------------------------ #

    def get_key(self, key_id: str) -> Dict[str, Any]:
        """Return a copy of one key."""
        if key_id not in self._keys:
            raise KeyError("unknown key_id: %s" % key_id)
        return copy.deepcopy(self._keys[key_id])

    def get_keys_for_concept(self, tag: str) -> List[Dict[str, Any]]:
        """All keys related to a concept tag (empty list if none)."""
        key_ids = self._concept_index.get(str(tag).strip().lower(), set())
        return [copy.deepcopy(self._keys[k]) for k in sorted(key_ids)]

    def get_prerequisite_chain(self, key_id: str) -> List[str]:
        """Walk the prerequisite graph breadth-first: immediate prerequisites
        first, then their prerequisites, and so on. Cycle-safe."""
        if key_id not in self._keys:
            raise KeyError("unknown key_id: %s" % key_id)
        chain: List[str] = []
        seen = {key_id}
        frontier = list(self._keys[key_id]["prerequisite_keys"])
        while frontier:
            nxt: List[str] = []
            for kid in sorted(frontier):
                if kid in seen:
                    continue
                seen.add(kid)
                chain.append(kid)
                nxt.extend(self._keys[kid]["prerequisite_keys"])
            frontier = nxt
        return chain

    def add_misconception(self, key_id: str, misconception: Dict[str, Any]) -> None:
        """Attach a misconception ``{"id", "description", "node_id"}`` to a key."""
        if key_id not in self._keys:
            raise KeyError("unknown key_id: %s" % key_id)
        entry = {
            "id": str(misconception.get("id", "")),
            "description": str(misconception.get("description", "")),
            "node_id": str(misconception.get("node_id", "")),
        }
        if not entry["id"]:
            raise ValueError("misconception requires an 'id'")
        existing = self._keys[key_id]["misconceptions"]
        if any(m["id"] == entry["id"] for m in existing):
            return
        existing.append(entry)

    # -- persistence and reporting ------------------------------------------ #

    def export(self) -> Dict[str, Any]:
        """Serialisable representation of the grid (keys only plus summary)."""
        keys = [copy.deepcopy(self._keys[k]) for k in sorted(self._keys)]
        return {
            "format": GRID_FORMAT,
            "key_count": len(keys),
            "node_count": len(self._nodes),
            "keys": keys,
        }

    def save(self, path: str) -> None:
        """Persist the grid (keys plus the indexes needed to reload it)."""
        payload = self.export()
        payload["index"] = {
            "concept_index": {
                tag: sorted(kids)
                for tag, kids in sorted(self._concept_index.items())
            },
            "prereq_graph": {
                node_id: sorted(prereqs)
                for node_id, prereqs in sorted(self._prereq_graph.items())
            },
            "nodes": sorted(self._nodes.values(), key=lambda n: n["node_id"]),
            "chapter_outcomes": [
                {
                    "subject": subject,
                    "class_level": class_level,
                    "chapter": chapter,
                    "outcomes": outcomes,
                }
                for (subject, class_level, chapter), outcomes in sorted(
                    self._chapter_outcomes.items()
                )
            ],
        }
        directory = os.path.dirname(os.path.abspath(path))
        if directory:
            os.makedirs(directory, exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(payload, fh, ensure_ascii=True, indent=2)

    def load(self, path: str) -> "KeyGrid":
        """Restore grid state previously written by :meth:`save`. Returns self."""
        with open(path, "r", encoding="utf-8") as fh:
            payload = json.load(fh)
        if payload.get("format") != GRID_FORMAT:
            raise ValueError("not a %s payload: %r" % (GRID_FORMAT, payload.get("format")))
        self._keys = {k["key_id"]: k for k in payload.get("keys", [])}
        index = payload.get("index", {})
        self._concept_index = {
            tag: set(kids) for tag, kids in index.get("concept_index", {}).items()
        }
        self._prereq_graph = {
            node_id: list(prereqs)
            for node_id, prereqs in index.get("prereq_graph", {}).items()
        }
        self._nodes = {
            n["node_id"]: n for n in index.get("nodes", []) if n.get("node_id")
        }
        self._chapter_outcomes = {}
        for rec in index.get("chapter_outcomes", []):
            group = (rec["subject"], int(rec["class_level"]), rec["chapter"])
            self._chapter_outcomes[group] = rec["outcomes"]
        self.skipped_files = []
        return self

    def coverage_report(self) -> Dict[str, Any]:
        """Per-chapter: total keys, keys per cognitive move, coverage gaps."""
        buckets: Dict[str, Dict[str, Any]] = {}
        for key in self._keys.values():
            cid = "%s|%d|%s" % (key["subject"], key["class_level"], key["chapter"])
            bucket = buckets.setdefault(
                cid,
                {
                    "total_keys": 0,
                    "per_move": {move: 0 for move in COGNITIVE_MOVES},
                    "learning_outcomes": set(),
                },
            )
            bucket["total_keys"] += 1
            bucket["per_move"][key["cognitive_move"]] += 1
            bucket["learning_outcomes"].add(key["learning_outcome"])

        chapters: Dict[str, Any] = {}
        total_gaps = 0
        for cid in sorted(buckets):
            bucket = buckets[cid]
            gaps = [m for m in COGNITIVE_MOVES if bucket["per_move"][m] == 0]
            total_gaps += len(gaps)
            chapters[cid] = {
                "total_keys": bucket["total_keys"],
                "keys_per_cognitive_move": dict(bucket["per_move"]),
                "learning_outcomes": len(bucket["learning_outcomes"]),
                "coverage_gaps": gaps,
            }
        return {
            "chapters": chapters,
            "summary": {
                "total_keys": len(self._keys),
                "total_chapters": len(chapters),
                "total_gaps": total_gaps,
            },
        }

    # -- conveniences -------------------------------------------------------- #

    def key_ids(self) -> List[str]:
        return sorted(self._keys)

    def chapter_count(self) -> int:
        return len(self._chapter_outcomes)

    def __len__(self) -> int:
        return len(self._keys)

    def __contains__(self, key_id: object) -> bool:
        return key_id in self._keys
