def g(steps_list):
    return [dict(step=i + 1, action=a, explain=e) for i, (a, e) in enumerate(steps_list)]


def cat(stem, title, concepts, questions, exsrc, exqs, w1, w2):
    wes = [
        we("ex1", "%s.%s.1" % (stem[:4].lower(), stem[-2:].lstrip("0") or "1"),
           "%s.txt" % stem, "verify_property", w1[0], {}, g(w1[1])),
        we("ex2", "%s.%s.2" % (stem[:4].lower(), stem[-2:].lstrip("0") or "1"),
           "%s.txt" % stem, "verify_property", w2[0], {}, g(w2[1])),
    ]
    exercises = [exr("ex1", "%s.txt, %s" % (stem, exsrc), questions + exqs)]
    p = build(stem, 6, "social_science", title, concepts, wes, exercises)
    print("wrote", p)


