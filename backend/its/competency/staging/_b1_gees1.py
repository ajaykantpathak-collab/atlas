def steps_cmp():
    return steps(
        ("set the two sides", "Write the two ideas, places or periods side by side."),
        ("mark what differs", "Note the points on which they differ and one point they share."),
        ("conclude", "State in one line what the comparison teaches."))


def cat(stem, title, concepts, questions, exsrc, exqs, wex=None):
    cid1 = "gees.%s.1" % (stem[-2:].lstrip("0") or "1")
    cid2 = "gees.%s.2" % (stem[-2:].lstrip("0") or "1")
    src = "%s.txt" % stem
    if wex and isinstance(wex, tuple):
        q, stp = wex
        wex = [we("ex1", cid1, src, "verify_property", q, {}, steps(*stp))]
    wes = (wex or []) + [
        we("ex2", cid2, src, "verify_property", questions[1].lower(), {}, steps_a()),
    ]
    p = build(stem, 7, "social_science", title, concepts, wes,
              [exr("ex1", "%s.txt, %s" % (stem, exsrc), questions + exqs)])
    print("wrote", p)


