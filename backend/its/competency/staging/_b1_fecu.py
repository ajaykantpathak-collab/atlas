def steps_a():
    return steps(
        ("state the idea", "Say what the concept means in one or two lines."),
        ("ground it in the chapter", "Recall the activity or example in the chapter that shows it."),
        ("apply it", "Use the idea on a new example from your surroundings."))


def steps_b():
    return steps(
        ("list the parts or steps", "Write out the parts, kinds or steps involved."),
        ("connect them", "Say how one part leads to the next or one kind differs from the other."),
        ("sum up", "Give the overall picture in one sentence."))


def steps_obs():
    return steps(
        ("observe closely", "Note the colour, shape, feel or behaviour of the thing studied."),
        ("record and group", "Write the observations in a table and group alike things together."),
        ("conclude", "State the pattern your observations reveal."))


def cat(stem, title, concepts, questions, exqs, wex=None):
    ch = stem[-2:].lstrip("0") or "1"
    src = "%s.txt" % stem
    if wex:
        wex = [we(w[0], "fecu.%s.%s" % (ch, w[1]), src, "compute", w[2], w[3], steps(*w[4]))
               for w in wex]
    else:
        wex = [we("ex1", "fecu.%s.1" % ch, src, "verify_property", questions[0].lower(), {}, steps_a())]
    wex = wex + [we("ex2", "fecu.%s.2" % ch, src, "verify_property", questions[1].lower(), {}, steps_b())]
    p = build(stem, 6, "science", title, concepts, wex,
              [exr("ex1", "%s.txt, Let us enhance our learning" % stem, questions + exqs)])
    print("wrote", p)


