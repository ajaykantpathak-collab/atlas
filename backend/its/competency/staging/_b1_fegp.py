def cat(stem, title, concepts, questions, wex=None):
    wes = []
    for w in (wex or []):
        wes.append(we(w[0], "fegp.%s.%s" % (stem[-2:].lstrip("0") or "1", w[1]),
                      "%s.txt" % stem, "compute", w[2], w[3], steps(*w[4])))
    if not wes:
        wes = [we("ex1", "fegp.%s.1" % (stem[-2:].lstrip("0") or "1"), "%s.txt" % stem,
                  "verify_property", questions[0].lower(), {}, steps_a())]
    wes.append(we("ex2", "fegp.%s.2" % (stem[-2:].lstrip("0") or "1"), "%s.txt" % stem,
                  "verify_property", questions[1].lower(), {}, steps_obs()))
    p = build(stem, 6, "maths", title, concepts, wes,
              [exr("ex1", "%s.txt, Figure it Out" % stem, questions)])
    print("wrote", p)


