def steps_b():
    return steps(
        ("list the parts or steps", "Write out the parts, kinds or steps involved."),
        ("connect them", "Say how one part leads to the next or one kind differs from the other."),
        ("sum up", "Give the overall picture in one sentence."))


def steps_obs():
    return steps(
        ("observe the change or behaviour", "Note exactly what happens in the activity."),
        ("record the pattern", "Write down which cases show it and which do not."),
        ("conclude", "State the rule your observations reveal."))


def steps_cmp():
    return steps(
        ("set the two sides", "Write the two ideas or groups side by side."),
        ("mark what differs", "Note the points on which they differ and one point they share."),
        ("conclude", "State in one line what the comparison teaches."))



def cat(stem, title, concepts, questions, exqs, wex=None):
    ch = stem[-2:].lstrip("0") or "1"
    src = "%s.txt" % stem
    if wex:
        wex = [we(w[0], "gecu.%s.%s" % (ch, w[1]), src, "compute", w[2], w[3], steps(*w[4]))
               for w in wex]
    else:
        wex = [we("ex1", "gecu.%s.1" % ch, src, "verify_property", questions[0].lower(), {}, steps_a())]
    wex = wex + [we("ex2", "gecu.%s.2" % ch, src, "verify_property", questions[1].lower(), {}, steps_b())]
    p = build(stem, 7, "science", title, concepts, wex,
              [exr("ex1", "%s.txt, Let us enhance our learning" % stem, questions + exqs)])
    print("wrote", p)


