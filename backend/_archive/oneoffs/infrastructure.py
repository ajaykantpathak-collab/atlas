_RATE_LIMIT_EXEMPT = {"/health", "/health/detailed", "/docs", "/openapi.json", "/redoc"}


class RateLimitMiddleware:
    """ASGI middleware enforcing per-IP and per-user rate limits."""

    def __init__(self, app: Any) -> None:
        self.app = app

    async def __call__(self, scope: Any, receive: Any, send: Any) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        path = scope.get("path", "")
        if path in _RATE_LIMIT_EXEMPT:
            await self.app(scope, receive, send)
            return

        redis_client = ConnectionPools.redis_client
        if redis_client is None:
            await self.app(scope, receive, send)
            return

        # Extract client IP
        client_ip = "unknown"
        if scope.get("client"):
            client_ip = scope["client"][0]

        # Extract user ID from headers
        user_id = "anonymous"
        for name, value in scope.get("headers", []):
            if name == b"x-user-id":
                user_id = value.decode()
                break

        ip_limiter = RateLimiter(redis_client, RATE_LIMIT_PER_IP)
        user_limiter = RateLimiter(redis_client, RATE_LIMIT_PER_USER)

        ip_ok, ip_retry = await ip_limiter.is_allowed("ip", client_ip)
        if not ip_ok:
            response = JSONResponse(
                {"detail": "Rate limit exceeded (per-IP)"},
                status_code=429,
                headers={"Retry-After": str(ip_retry)},
            )
            await response(scope, receive, send)
            return

        user_ok, user_retry = await user_limiter.is_allowed("user", user_id)
        if not user_ok:
            response = JSONResponse(
                {"detail": "Rate limit exceeded (per-user)"},
                status_code=429,
                headers={"Retry-After": str(user_retry)},
            )
            await response(scope, receive, send)
            return

        await self.app(scope, receive, send)


