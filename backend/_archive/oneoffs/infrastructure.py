class RateLimiter:
    """Redis-backed sliding-window rate limiter."""

    _WINDOW: int = 60  # seconds

    def __init__(self, redis_client: aioredis.Redis, limit: int) -> None:
        self._redis = redis_client
        self._limit = limit

    def _key(self, scope: str, identifier: str) -> str:
        return f"ratelimit:{scope}:{identifier}"

    async def is_allowed(self, scope: str, identifier: str) -> tuple[bool, int]:
        """Return (allowed, retry_after_seconds)."""
        key = self._key(scope, identifier)
        now = time.time()
        window_start = now - self._WINDOW

        try:
            pipe = self._redis.pipeline()
            pipe.zremrangebyscore(key, 0, window_start)
            pipe.zcard(key)
            pipe.zadd(key, {str(now): now})
            pipe.expire(key, self._WINDOW)
            results = await pipe.execute()

            count: int = results[1]
            if count >= self._limit:
                retry_after = self._WINDOW - int(now - window_start)
                return False, max(retry_after, 1)
            return True, 0
        except Exception:
            logger.warning("Rate-limit Redis failure; allowing request")
            return True, 0


