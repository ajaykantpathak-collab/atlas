def _build_cache_key(path: str, query_params: dict[str, Any], user_id: str) -> str:
    """Derive a deterministic cache key from request identity fields."""
    params_str = "&".join(f"{k}={v}" for k, v in sorted(query_params.items()))
    raw = f"{path}|{params_str}|{user_id}"
    digest = hashlib.sha256(raw.encode()).hexdigest()[:32]
    return f"cache:{digest}"


def cache(
    ttl: int | None = None,
) -> Callable[[Callable[..., Any]], Callable[..., Any]]:
    """Decorator that caches GET endpoint results in Redis.

    Falls back to calling the underlying function when Redis is unreachable.
    """
    default_ttl = ttl if ttl is not None else CACHE_TTL_SECONDS

    def decorator(func: Callable[..., Any]) -> Callable[..., Any]:
        @functools.wraps(func)
        async def wrapper(*args: Any, **kwargs: Any) -> Any:
            request: Request | None = kwargs.get("request") or (
                args[0] if args and isinstance(args[0], Request) else None
            )
            user_id: str = kwargs.get("user_id", "anonymous")

            if request is None:
                return await func(*args, **kwargs)

            key = _build_cache_key(
                request.url.path,
                dict(request.query_params),
                user_id,
            )

            # Try Redis first
            if ConnectionPools.redis_client is not None:
                try:
                    cached = await ConnectionPools.redis_client.get(key)
                    if cached is not None:
                        logger.debug("Cache hit  key=%s", key)
                        return json.loads(cached)
                except Exception:
                    logger.warning("Redis read failed; falling back to DB")

            # Cache miss or Redis down
            result = await func(*args, **kwargs)

            # Write back to Redis
            if ConnectionPools.redis_client is not None:
                try:
                    await ConnectionPools.redis_client.set(
                        key,
                        json.dumps(result, default=str),
                        ex=default_ttl,
                    )
                    logger.debug("Cache set  key=%s ttl=%d", key, default_ttl)
                except Exception:
                    logger.warning("Redis write failed; continuing without cache")

            return result

        return wrapper

    return decorator


async def invalidate_cache_prefix(prefix: str) -> int:
    """Best-effort cache invalidation by scanning keys with a prefix."""
    if ConnectionPools.redis_client is None:
        return 0
    try:
        deleted = 0
        async for key in ConnectionPools.redis_client.scan_iter(
            match=f"cache:*", count=100
        ):
            await ConnectionPools.redis_client.delete(key)
            deleted += 1
        return deleted
    except Exception:
        logger.warning("Cache invalidation failed")
        return 0


