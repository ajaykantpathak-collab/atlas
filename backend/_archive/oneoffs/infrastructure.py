class ServiceHealth(BaseModel):
    """Health status of a single service."""

    service: str
    status: str  # "healthy" | "unhealthy"
    latency_ms: float
    detail: str = ""


class HealthAggregator:
    """Checks health of Postgres, Neo4j, Redis, and Qdrant concurrently."""

    def __init__(self, timeout_s: float = 3.0) -> None:
        self._timeout = timeout_s

    async def _check_postgres(self) -> ServiceHealth:
        if ConnectionPools.pg_engine is None:
            return ServiceHealth(
                service="postgres", status="unhealthy", latency_ms=0.0,
                detail="not initialised",
            )
        start = time.perf_counter()
        try:
            async with asyncio.timeout(self._timeout):
                async with ConnectionPools.pg_engine.connect() as conn:
                    await conn.execute(text("SELECT 1"))
            latency = (time.perf_counter() - start) * 1000
            return ServiceHealth(
                service="postgres", status="healthy",
                latency_ms=round(latency, 2),
            )
        except Exception as exc:
            latency = (time.perf_counter() - start) * 1000
            return ServiceHealth(
                service="postgres", status="unhealthy",
                latency_ms=round(latency, 2), detail=str(exc),
            )

    async def _check_neo4j(self) -> ServiceHealth:
        driver = ConnectionPools.neo4j_driver
        if driver is None:
            return ServiceHealth(
                service="neo4j", status="unhealthy", latency_ms=0.0,
                detail="not initialised",
            )
        start = time.perf_counter()
        try:
            async with asyncio.timeout(self._timeout):
                async with driver.session() as session:
                    result = await session.run("RETURN 1")
                    await result.consume()
            latency = (time.perf_counter() - start) * 1000
            return ServiceHealth(
                service="neo4j", status="healthy",
                latency_ms=round(latency, 2),
            )
        except Exception as exc:
            latency = (time.perf_counter() - start) * 1000
            return ServiceHealth(
                service="neo4j", status="unhealthy",
                latency_ms=round(latency, 2), detail=str(exc),
            )

    async def _check_redis(self) -> ServiceHealth:
        client = ConnectionPools.redis_client
        if client is None:
            return ServiceHealth(
                service="redis", status="unhealthy", latency_ms=0.0,
                detail="not initialised",
            )
        start = time.perf_counter()
        try:
            async with asyncio.timeout(self._timeout):
                await client.ping()
            latency = (time.perf_counter() - start) * 1000
            return ServiceHealth(
                service="redis", status="healthy",
                latency_ms=round(latency, 2),
            )
        except Exception as exc:
            latency = (time.perf_counter() - start) * 1000
            return ServiceHealth(
                service="redis", status="unhealthy",
                latency_ms=round(latency, 2), detail=str(exc),
            )

    async def _check_qdrant(self) -> ServiceHealth:
        start = time.perf_counter()
        try:
            import httpx

            async with asyncio.timeout(self._timeout):
                async with httpx.AsyncClient() as http_client:
                    resp = await http_client.get(f"{QDRANT_URL}/collections")
                    resp.raise_for_status()
            latency = (time.perf_counter() - start) * 1000
            return ServiceHealth(
                service="qdrant", status="healthy",
                latency_ms=round(latency, 2),
            )
        except Exception as exc:
            latency = (time.perf_counter() - start) * 1000
            return ServiceHealth(
                service="qdrant", status="unhealthy",
                latency_ms=round(latency, 2), detail=str(exc),
            )

    async def check_all(self) -> Dict[str, Any]:
        """Run all checks concurrently and return a composite report."""
        results = await asyncio.gather(
            self._check_postgres(),
            self._check_neo4j(),
            self._check_redis(),
            self._check_qdrant(),
            return_exceptions=False,
        )

        services: Dict[str, ServiceHealth] = {r.service: r for r in results}
        statuses = {s.status for s in services.values()}

        if statuses == {"healthy"}:
            overall = "healthy"
        elif "unhealthy" in statuses and "healthy" in statuses:
            overall = "degraded"
        elif statuses == {"unhealthy"}:
            overall = "unhealthy"
        else:
            overall = "degraded"

        from datetime import datetime, timezone

        return {
            "status": overall,
            "services": {k: v.model_dump() for k, v in services.items()},
            "timestamp": datetime.now(timezone.utc).isoformat(),
        }


