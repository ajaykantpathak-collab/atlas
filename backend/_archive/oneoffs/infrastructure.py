def init_infrastructure(app: FastAPI) -> None:
    """Wire up all infrastructure: pools, middleware, health endpoints."""
    # Connection pools
    ConnectionPools.init_postgres()
    ConnectionPools.init_neo4j()
    ConnectionPools.init_redis()

    # Middleware (ASGI-level)
    app.add_middleware(RateLimitMiddleware)

    # Detailed health endpoint
    aggregator = HealthAggregator()

    @app.get("/health/detailed", tags=["health"])
    async def health_detailed() -> JSONResponse:
        report = await aggregator.check_all()
        status_code = 200 if report["status"] != "unhealthy" else 503
        return JSONResponse(report, status_code=status_code)

    logger.info("Infrastructure initialised: pools, rate limiter, health checks")
