async def get_db_session() -> AsyncGenerator[AsyncSession, None]:
    """Yield an async DB session from the shared pool."""
    if ConnectionPools.pg_session_factory is None:
        raise RuntimeError("Postgres pool not initialised")
    async with ConnectionPools.pg_session_factory() as session:
        try:
            yield session
        finally:
            await session.close()


