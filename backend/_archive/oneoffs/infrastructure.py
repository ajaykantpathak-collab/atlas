class ConnectionPools:
    """Holds shared async connection pools for all backing services."""

    pg_engine: AsyncEngine | None = None
    pg_session_factory: async_sessionmaker[AsyncSession] | None = None
    neo4j_driver: Any | None = None  # neo4j.AsyncDriver
    redis_pool: aioredis.ConnectionPool | None = None
    redis_client: aioredis.Redis | None = None

    @classmethod
    def init_postgres(cls) -> None:
        """Create the async SQLAlchemy engine and session factory."""
        if cls.pg_engine is not None:
            return
        cls.pg_engine = create_async_engine(
            DATABASE_URL,
            pool_size=DB_POOL_SIZE,
            max_overflow=DB_MAX_OVERFLOW,
            pool_pre_ping=True,
            pool_recycle=3600,
            echo=False,
        )
        cls.pg_session_factory = async_sessionmaker(
            cls.pg_engine, expire_on_commit=False
        )
        logger.info(
            "Postgres pool initialised (size=%d, overflow=%d)",
            DB_POOL_SIZE,
            DB_MAX_OVERFLOW,
        )

    @classmethod
    def init_neo4j(cls) -> None:
        """Create the async Neo4j driver."""
        if cls.neo4j_driver is not None:
            return
        try:
            from neo4j import AsyncGraphDatabase

            cls.neo4j_driver = AsyncGraphDatabase.driver(
                NEO4J_URI,
                auth=(NEO4J_USER, NEO4J_PASSWORD),
                max_connection_pool_size=50,
            )
            logger.info("Neo4j driver initialised (%s)", NEO4J_URI)
        except ImportError:
            logger.warning("neo4j package not installed; skipping Neo4j pool")

    @classmethod
    def init_redis(cls) -> None:
        """Create the async Redis connection pool and client."""
        if cls.redis_client is not None:
            return
        cls.redis_pool = aioredis.ConnectionPool.from_url(
            REDIS_URL,
            max_connections=200,
            decode_responses=True,
        )
        cls.redis_client = aioredis.Redis(connection_pool=cls.redis_pool)
        logger.info("Redis pool initialised (max_connections=200)")

    @classmethod
    async def close_all(cls) -> None:
        """Gracefully close every pool (call on shutdown)."""
        if cls.pg_engine:
            await cls.pg_engine.dispose()
            cls.pg_engine = None
            cls.pg_session_factory = None
        if cls.neo4j_driver:
            await cls.neo4j_driver.close()
            cls.neo4j_driver = None
        if cls.redis_client:
            await cls.redis_client.aclose()
            cls.redis_client = None
            cls.redis_pool = None
        logger.info("All connection pools closed")


