"""SQLAlchemy model for the solver template store.

Stores multi-step problem templates that are generated by the LLM orchestrator
and reused for future questions of the same pattern.
"""

import uuid
from datetime import datetime, timezone

from sqlalchemy import Column, String, Integer, DateTime, Text, Float
from sqlalchemy.types import TIMESTAMP
from backend.db_types import GUID, JSONVariant
from sqlalchemy.orm import declarative_base

Base = declarative_base()


class SolverTemplate(Base):
    """A reusable multi-step problem template.

    When a student asks a multi-step question that the compute engine can't
    handle in one shot, the LLM orchestrator decomposes it into steps. The
    decomposition is saved here so future questions of the same pattern
    (with different numbers) can be solved without calling the LLM again.
    """
    __tablename__ = "solver_templates"

    id = Column(GUID(), primary_key=True, default=uuid.uuid4)

    # Human-readable identifier for the pattern
    template_name = Column(String(200), nullable=False)

    # The normalized question pattern (numbers replaced with placeholders)
    # e.g. "rectangular sheet area NUM length RATIO times width cut squares side x fold maximize volume"
    normalized_pattern = Column(Text, nullable=False)

    # The original question that generated this template
    original_question = Column(Text, nullable=False)

    # The step decomposition (JSON array of {step, command, purpose})
    steps = Column(JSONVariant(), nullable=False)

    # Variables that can be extracted from new questions (e.g. ["area", "ratio"])
    variables = Column(JSONVariant(), default=list)

    # Embedding of the normalized pattern (stored as JSON array of floats)
    # Using all-MiniLM-L6-v2 → 384 dimensions
    embedding = Column(JSONVariant(), nullable=True)

    # Metadata
    subject = Column(String(50), nullable=True)
    class_level = Column(Integer, nullable=True)

    # Usage stats
    times_used = Column(Integer, default=0)
    created_at = Column(TIMESTAMP(timezone=True), default=lambda: datetime.now(timezone.utc))
    last_used_at = Column(TIMESTAMP(timezone=True), nullable=True)

    def __repr__(self):
        return f"<SolverTemplate {self.template_name} (used {self.times_used}x)>"
