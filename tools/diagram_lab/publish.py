"""publish.py — compile validated diagram .md files into the frontend.

Reads  assets/diagram_lab/md_*/<slug>.md  +  assets.json attribution
Writes frontend/public/diagrams/<slug>.<ext>  (copied image)
       frontend/components/sims_v2/engine/diagrams.ts  (DIAGRAMS registry)

Each registry entry: { image, credit, title, explain, exam[], parts[] }.
Sims mount them via LABS['dgm_<slug>'] — auto-registered in canvasLab.
"""
import os, sys, glob, json, shutil
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from validate import parse_md, validate

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MD_GLOB = os.path.join(ROOT, 'assets', 'diagram_lab', 'md_*', '*.md')
IMG_DIR = os.path.join(ROOT, 'assets', 'diagram_lab', 'img')
OUT_IMG = os.path.join(ROOT, 'frontend', 'public', 'diagrams')
OUT_TS = os.path.join(ROOT, 'frontend', 'components', 'sims_v2', 'engine', 'diagrams.ts')
ASSETS = os.path.join(ROOT, 'assets', 'diagram_lab', 'img', 'assets.json')


def main():
    os.makedirs(OUT_IMG, exist_ok=True)
    credits = json.load(open(ASSETS)) if os.path.exists(ASSETS) else {}
    entries, skipped = [], []
    for md in sorted(glob.glob(MD_GLOB)):
        slug = os.path.basename(md)[:-3]
        err, doc = parse_md(open(md, encoding='utf-8').read())
        if err or doc.get('not_a_diagram'):
            skipped.append(slug); continue
        errs = validate(doc)
        if errs:
            skipped.append(f'{slug}: {"; ".join(errs)[:80]}'); continue
        img = None
        for ext in ('.png', '.jpg', '.svg'):
            cand = os.path.join(IMG_DIR, slug + ext)
            if os.path.exists(cand):
                img = slug + ext
                shutil.copy(cand, os.path.join(OUT_IMG, img))
                break
        if not img:
            skipped.append(f'{slug}: no image'); continue
        cr = credits.get(slug, {})
        credit = f"{cr.get('src','Wikimedia').replace('File:','')} · {cr.get('license','')}"
        entries.append((slug, img, credit, doc))
    # emit TS
    out = ['// GENERATED by tools/diagram_lab/publish.py — do not edit',
           'export interface DgmPart { id: string; label: string; x: number; y: number; r: number; fn: string }',
           'export const DIAGRAMS: Record<string, { image: string; credit: string; title: string; explain: string; exam: string[]; parts: DgmPart[] }> = {']
    for slug, img, credit, doc in entries:
        parts = ', '.join("{id:'%s',label:'%s',x:%.3f,y:%.3f,r:%.3f,fn:'%s'}" % (
            p['id'], p['label'].replace("'", "\\'"), p['x'], p['y'], p['r'],
            p['fn'].replace("'", "\\'")) for p in doc['parts'])
        exam = json.dumps(doc.get('exam', []))
        out.append("  '%s': { image: '/diagrams/%s', credit: %s, title: %s, explain: %s, exam: %s, parts: [%s] }," % (
            slug, img, json.dumps(credit), json.dumps(doc['name']),
            json.dumps(doc.get('explain', '')), exam, parts))
    out.append('};\n')
    open(OUT_TS, 'w', encoding='utf-8').write('\n'.join(out))
    print(f'published {len(entries)} diagrams -> {OUT_TS}')
    for s in skipped:
        print('  skipped:', s)


if __name__ == '__main__':
    main()
