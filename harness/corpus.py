"""corpus.py — append-only regression corpus (§11) + pinned checks.

cases.jsonl is append-only: cases are never deleted. Status transitions
(red -> green, anything -> parked) rewrite ONLY the status/reason fields
of that case's line and append an audit record to corpus/history.jsonl.
Pinned checks live in deploy/backend/tests/corpus/ and run inside G1, so
the corpus protects itself on every future batch.
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Dict, List, Optional

import common as C

PINNED_TEMPLATE = '''"""Pinned corpus check {cid} (generated by harness corpus add).

Case origin: {origin}
added_because: {added_because}
status at pin time: {status}
"""
import json
import os
import sys

_DEPLOY = r"D:\\platform\\deploy"
if os.path.isdir(_DEPLOY):  # native runs pin the deploy tree explicitly;
    sys.path.insert(0, _DEPLOY)  # in-container runs resolve via cwd (/app)

CASE = json.loads(r"""
{case}
""")

def test_corpus_case():
    {body}
'''


def cases_path(cfg: Dict[str, Any]) -> Path:
    return C.cfg_path(cfg, "corpus_cases")


def history_path(cfg: Dict[str, Any]) -> Path:
    return cases_path(cfg).parent / "history.jsonl"


def load_cases(cfg: Dict[str, Any]) -> List[Dict[str, Any]]:
    return C.read_jsonl(cases_path(cfg))


def next_case_id(cfg: Dict[str, Any]) -> str:
    ids = [c.get("id", "") for c in load_cases(cfg)]
    nums = [int(m.group(1)) for i in ids
            if (m := re.match(r"COR-(\d{6})$", i))]
    return f"COR-{max(nums, default=0) + 1:06d}"


def question_hash(text: str) -> str:
    norm = re.sub(r"\s+", " ", text.strip().lower())
    return C.sha256_bytes(norm.encode("utf-8"))[:16]


def add_case(cfg: Dict[str, Any], *, source: str, origin: Dict[str, Any],
             question_text: str, expected: Dict[str, Any],
             added_because: str, status: str = "red",
             write_pinned: bool = True) -> Dict[str, Any]:
    # dedupe: same normalized question hash never enters twice
    qh = question_hash(question_text)
    for c in load_cases(cfg):
        if c.get("question_hash") == qh:
            return {"case": c, "deduped": True}
    cid = next_case_id(cfg)
    case = {
        "id": cid, "added_utc": C.iso_utc(), "source": source,
        "origin": origin, "question_text": question_text,
        "question_hash": qh, "expected": expected,
        "pinned_check": f"tests/corpus/test_{cid}.py",
        "status": status, "added_because": added_because,
    }
    C.append_jsonl(cases_path(cfg), case)
    C.append_jsonl(history_path(cfg), {"ts_utc": C.iso_utc(), "action": "add",
                                       "id": cid, "status": status})
    if write_pinned:
        write_pinned_check(cfg, case)
    return {"case": case, "deduped": False}


PINNED_SKIPPED = '''"""Pinned corpus check {cid} — PARKED.

Parked because: {reason}
Pinned at: {ts}
The case stays visible as debt; it is skipped, never deleted (§11).
"""
import pytest


def test_corpus_case_parked():
    pytest.skip("CORPUS PARKED {cid}: {reason}")
'''


def set_status(cfg: Dict[str, Any], case_id: str, status: str,
               reason: str = "") -> Dict[str, Any]:
    """Status transition on one case line (never deletes). Parking rewrites
    the pinned check as a module-level skip with the reason."""
    path = cases_path(cfg)
    rows = C.read_jsonl(path)
    hit = None
    for r in rows:
        if r.get("id") == case_id:
            r["status"] = status
            r["status_reason"] = reason
            r["status_ts_utc"] = C.iso_utc()
            hit = r
            break
    if hit is None:
        raise KeyError(f"no such case: {case_id}")
    with open(path, "w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    C.append_jsonl(history_path(cfg), {"ts_utc": C.iso_utc(),
                                       "action": "status", "id": case_id,
                                       "status": status, "reason": reason})
    if status == "parked":
        pinned = C.cfg_path(cfg, "corpus_pinned_dir") / f"test_{case_id}.py"
        if pinned.exists():
            pinned.write_text(PINNED_SKIPPED.format(
                cid=case_id, reason=reason or "parked", ts=C.iso_utc()),
                encoding="utf-8")
    return hit


def write_pinned_check(cfg: Dict[str, Any], case: Dict[str, Any]) -> Path:
    pinned_dir = C.cfg_path(cfg, "corpus_pinned_dir")
    pinned_dir.mkdir(parents=True, exist_ok=True)
    body = _pinned_body(case)
    path = pinned_dir / f"test_{case['id']}.py"
    path.write_text(PINNED_TEMPLATE.format(
        cid=case["id"], origin=json.dumps(case.get("origin", {}))[:200],
        added_because=case.get("added_because", ""), status=case["status"],
        case=json.dumps({k: case[k] for k in ("id", "question_text",
                                              "expected")}, indent=2,
                        ensure_ascii=False),
        body=body), encoding="utf-8")
    (pinned_dir / "__init__.py").write_text("", encoding="utf-8")
    return path


def _pinned_body(case: Dict[str, Any]) -> str:
    exp = case.get("expected", {})
    if exp.get("structure") is not None:
        return ("from backend.its.solver import modeling_layer as ml\n"
                "    r = ml.model_problem(CASE['question_text'])\n"
                "    matched = getattr(r, 'matched', False)\n"
                f"    assert matched, f'case {{CASE[\"id\"]}} still unmatched'\n"
                f"    assert getattr(r, 'structure', None) == {exp['structure']!r}")
    return ("from backend.its.solver import modeling_layer as ml\n"
            "    r = ml.model_problem(CASE['question_text'])\n"
            "    matched = getattr(r, 'matched', False)\n"
            f"    assert matched, f'case {{CASE[\"id\"]}} still refuses to model'")


def summary(cfg: Dict[str, Any]) -> Dict[str, int]:
    out = {"red": 0, "green": 0, "parked": 0, "total": 0}
    for c in load_cases(cfg):
        out["total"] += 1
        st = c.get("status", "red")
        if st in out:
            out[st] += 1
    return out


def main_add_from(cfg: Dict[str, Any], candidates_path: Path,
                  pick: int = 1) -> List[Dict[str, Any]]:
    """corpus add --from candidates.jsonl: attach a real question_text to the
    top candidate(s). Telemetry lacks question text, so the caller (agent)
    must already have enriched candidates with question_text; entries
    without one are reported, not guessed."""
    added = []
    rows = [r for r in C.read_jsonl(candidates_path)
            if r.get("question_text")][:pick]
    for r in rows:
        res = add_case(cfg, source="telemetry", origin=r.get("origin", {}),
                       question_text=r["question_text"],
                       expected=r.get("expected", {"tier": "VERIFIED"}),
                       added_because=r.get("added_because",
                                           r.get("signature", "mined")))
        added.append(res)
    return added
