// ─── Lint + emit ────────────────────────────────────────────────────────────
let warnings = [];
for (const g of games) {
  if (g.slides.length !== 5) lintErrors.push(`${g.file}: slideCount ${g.slides.length} != 5`);
  if (g.challenges.length !== 8) lintErrors.push(`${g.file}: challengeCount ${g.challenges.length} != 8`);
  g.challenges.forEach((c, i) => {
    if (!c.type.startsWith('sort')) {
      if (!Array.isArray(c.options) || c.options.length < 3) lintErrors.push(`${g.file}[${i}]: options < 3`);
      if (!c.options || !c.options.includes(c.answer)) lintErrors.push(`${g.file}[${i}]: answer "${c.answer}" not in options`);
    } else {
      if (!c.sortItems || !c.sortItems.length) lintErrors.push(`${g.file}[${i}]: sort missing sortItems`);
      if (!c.bins || !c.bins.length) lintErrors.push(`${g.file}[${i}]: sort missing bins`);
      const binIds = new Set((c.bins || []).map(b => b.id));
      for (const si of c.sortItems || []) if (!binIds.has(si.correctBin)) lintErrors.push(`${g.file}[${i}]: sortItem "${si.label}" -> unknown bin ${si.correctBin}`);
    }
    lintQuestion(g.gameFile, i, c.question);
  });
}

if (lintErrors.length) {
  console.error('LINT FAILURES:');
  lintErrors.forEach(e => console.error('  -', e));
  process.exit(1);
}

