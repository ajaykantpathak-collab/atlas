let lintErrors = [];
function lintQuestion(gameFile, idx, q) {
  const ql = q.toLowerCase();
  for (const t of TRIGGERS) {
    if (ql.includes(t)) {
      lintErrors.push(`${gameFile} challenge[${idx}]: question contains "${t}" -> "${q.slice(0, 90)}..."`);
    }
  }
  if (/\d+\s*[+\-]\s*\d+/.test(ql) || /\d+\.\d+/.test(ql)) {
    lintErrors.push(`${gameFile} challenge[${idx}]: question has arithmetic/decimal pattern -> "${q.slice(0, 90)}..."`);
  }
}

// ─── Challenge builders ─────────────────────────────────────────────────────
const STORY_BEATS = ['setup', 'setup', 'inciting', 'inciting', 'rising', 'rising', 'climax', 'resolution'];

function mcq(type, question, answer, options, hint, misconception, easierDistractor) {
  return {
    type, question, answer, options: options.slice(), hint, misconception,
    ...(easierDistractor ? { easierVariant: { options: [answer, easierDistractor] } } : {}),
  };
}

function sortC(type, question, hint, misconception, items, bins) {
  return {
    type, question, answer: 'sort', options: [], hint, misconception,
    sortItems: items.map(i => ({ id: i.id, label: i.label, icon: i.emoji || i.label, emoji: i.emoji || '', correctBin: i.bin })),
    bins: bins.map(b => ({ id: b.id, label: b.label, color: b.color })),
  };
}

function slide(title, text, emoji, bgColor, spoken) {
  return { title, text, emoji, bgColor, spoken };
}

// ─── Game definitions ───────────────────────────────────────────────────────
const games = [];
function defGame(file, gameFile, classLevel, mascot, theme, artifact, slides, challenges) {
  games.push({ file, gameFile, classLevel, mascot, theme, artifact, slides, challenges });
}

